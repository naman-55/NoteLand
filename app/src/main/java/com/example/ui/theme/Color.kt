// Note Pastel & Gradient Card Palette
data class NoteColorPalette(
    val name: String,
    val hexCode: String,
    val lightBackground: Color,
    val darkBackground: Color,
    val lightGradient: List<Color>? = null,
    val darkGradient: List<Color>? = null
) {
    val isGradient: Boolean
        get() = lightGradient != null && darkGradient != null

    fun resolve(isDark: Boolean): Color = if (isDark) darkBackground else lightBackground

    fun resolveBrush(isDark: Boolean, fallbackColor: Color = lightBackground): Brush {
        val stops = if (isDark) darkGradient else lightGradient
        return when {
            stops != null && stops.size >= 2 -> Brush.linearGradient(colors = stops)
            hexCode.isNotEmpty() -> SolidColor(resolve(isDark))
            else -> SolidColor(fallbackColor)
        }
    }
}

