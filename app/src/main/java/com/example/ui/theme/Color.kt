fun findNoteStylePreset(key: String): NoteColorPalette? {
    if (key.isBlank()) return NoteColorPresets.first()
    return NoteColorPresets.firstOrNull { it.hexCode.equals(key, ignoreCase = true) }
        ?: NoteGradientPresets.firstOrNull { it.hexCode.equals(key, ignoreCase = true) }
}

fun resolveNoteBackgroundBrush(colorKey: String, isDark: Boolean, fallbackColor: Color): Brush {
    val preset = findNoteStylePreset(colorKey)
    return if (preset != null && preset.hexCode.isNotEmpty()) {
        preset.resolveBrush(isDark, fallbackColor)
    } else {
        SolidColor(fallbackColor)
    }
}

